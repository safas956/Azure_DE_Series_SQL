--PATINDEX GIVES THE INDEX OF THAT PARTICULAR CHARACTER
--%D%--CHARACTER CAN BE ANYWHERE
--D% -- IT WILL IDENTIFY THE LETTER STARTING WITH D
--%D -- IT WILL IDENTIFY THE LETTER ENDING WITH D

SELECT [CUSTOMER NAME], PATINDEX('%D%',[CUSTOMER NAME]) AS CUS_NAME_WITH_D FROM ORDERS

SELECT [CUSTOMER NAME], PATINDEX('D%',[CUSTOMER NAME]) AS CUS_NAME_WITH_D FROM ORDERS

SELECT [CUSTOMER NAME], PATINDEX('%D',[CUSTOMER NAME]) AS CUS_NAME_WITH_D FROM ORDERS

SELECT [CUSTOMER NAME],
	PATINDEX('%D%',[CUSTOMER NAME]) AS D_ANYWHERE,
	PATINDEX('D%',[CUSTOMER NAME]) AS STARTING_WITH_D,
	PATINDEX('%D',[CUSTOMER NAME]) AS ENDING_WITH_D
FROM ORDERS

